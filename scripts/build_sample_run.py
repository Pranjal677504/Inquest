"""Build the browser walkthrough from the published offline baseline archive."""

import hashlib
import json
from pathlib import Path
import tarfile


ROOT = Path(__file__).resolve().parents[1]
ARCHIVE = ROOT / "experiments/offline-baseline-v1/authored-run.tar.gz"
OUTPUT = ROOT / "public/assets/sample-run.js"
ARCHIVE_SHA256 = "6b3bc6a388b0747787f13e65c5d3432763f0f7be936a1f1ccfc5e48346c431bc"
JOB_IDS = ("case-0001-budget-005", "case-0003-budget-005")


def main() -> None:
    digest = hashlib.sha256(ARCHIVE.read_bytes()).hexdigest()
    if digest != ARCHIVE_SHA256:
        raise ValueError(f"Published baseline archive checksum changed: {digest}")

    with tarfile.open(ARCHIVE, "r:gz") as archive:
        def read(path: str) -> str:
            member = archive.getmember(f"authored/{path}")
            if not member.isfile():
                raise ValueError(f"Expected a regular file: {path}")
            stream = archive.extractfile(member)
            if stream is None:
                raise ValueError(f"Unable to read: {path}")
            return stream.read().decode("utf-8")

        manifest = json.loads(read("run.json"))
        jobs = [job for job in manifest["jobs"] if job["job_id"] in JOB_IDS]
        if tuple(job["job_id"] for job in jobs) != JOB_IDS:
            raise ValueError("Sample episode selection changed")
        # This is a clearly labeled excerpt. Preserve the source run's config and
        # fingerprint; narrow only its job list for the viewer's completion counts.
        manifest["jobs"] = jobs
        files = [{"path": "sample-investigations/run.json",
                  "content": json.dumps(manifest, separators=(",", ":")) + "\n"}]
        for job in jobs:
            base = f"episodes/{job['job_id']}"
            result = read(f"{base}/result.json")
            journal = read(f"{base}/attempt-001.jsonl")
            parsed_result = json.loads(result)
            if parsed_result["job_id"] != job["job_id"] or parsed_result["fingerprint"] != manifest["fingerprint"]:
                raise ValueError(f"Result identity changed: {job['job_id']}")
            if parsed_result["score"]["success"] != (job["job_id"] == JOB_IDS[0]):
                raise ValueError(f"Expected accepted and incorrect example: {job['job_id']}")
            files.extend((
                {"path": f"sample-investigations/{base}/result.json", "content": result},
                {"path": f"sample-investigations/{base}/attempt-001.jsonl", "content": journal},
            ))

    output = (
        "'use strict';\n"
        "// Curated two-episode excerpt from experiments/offline-baseline-v1/authored-run.tar.gz.\n"
        "// Generated by python scripts/build_sample_run.py; do not edit by hand.\n"
        "window.INQUEST_SAMPLE_FILES = "
        + json.dumps(files, ensure_ascii=True, separators=(",", ":"))
        + ";\n"
    )
    OUTPUT.write_text(output, encoding="utf-8")


if __name__ == "__main__":
    main()
